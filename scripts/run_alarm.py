"""The solar alarm: read the meter workbooks and name the plants in trouble.

    uv run python scripts/run_alarm.py
    uv run python scripts/run_alarm.py --as-of 2024-11

Reads the same two workbooks the Institute already keeps and reports, per
plant, whether it has stopped, is sliding, or is simply not being read.

The second form is the part worth showing anyone: run it with a date in the
past and it reports what it would have said **at that time**, using only what
was known by then. That turns "this tool would have caught it" from a claim
into something you can check.
"""

from __future__ import annotations

import argparse
import csv
import sys

sys.path.insert(0, "src")

from btp_solar import alarm, campus_meters, config

OUT = config.DATA / "plant_health.csv"
FIGURE = config.REPORTS / "figures" / "alarm_dashboard.png"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--as-of", default=None,
                        help="report as the alarm would have at this month, e.g. 2024-11")
    args = parser.parse_args()

    workbooks = sorted(config.DATA.glob(config.METER_WORKBOOK_GLOB))
    if not workbooks:
        print("no meter workbooks in data/")
        return 1

    plants = campus_meters.load(workbooks)
    every_month = alarm.months_in(plants)
    as_of = args.as_of or every_month[-1]
    if as_of not in every_month:
        print(f"{as_of} is outside the record ({every_month[0]} to {every_month[-1]})")
        return 1

    findings = alarm.assess(plants, as_of)
    counts = {s: sum(1 for f in findings if f.status == s)
              for s in (alarm.STOPPED, alarm.COLLAPSED, alarm.UNDERPERFORMING,
                        alarm.NOT_READ, alarm.HEALTHY, alarm.TOO_NEW)}

    print(f"Solar alarm, as of {as_of}")
    print(f"{len(plants)} plants, {len(every_month)} months of readings "
          f"({every_month[0]} to {every_month[-1]})\n")

    print(f"  stopped          {counts[alarm.STOPPED]}")
    print(f"  collapsed        {counts[alarm.COLLAPSED]}")
    print(f"  underperforming  {counts[alarm.UNDERPERFORMING]}")
    print(f"  not being read   {counts[alarm.NOT_READ]}")
    print(f"  generating       {counts[alarm.HEALTHY]}")
    print(f"  too new to judge {counts[alarm.TOO_NEW]}\n")

    for finding in findings:
        if finding.status in (alarm.HEALTHY, alarm.TOO_NEW):
            continue
        print(" ", finding)
        if finding.first_flagged and finding.first_flagged != as_of:
            missed = _months_between(finding.first_flagged, as_of)
            print(f"           this alarm would have fired in "
                  f"{finding.first_flagged}, {missed} months before now")

    lost = sum(f.lost_kwh for f in findings)
    if lost:
        print(f"\n  Not generated by the stopped plants: {lost / 1000:,.0f} MWh, "
              f"about Rs {lost * config.TARIFF_INR_PER_KWH / 1e5:,.0f} lakh")
        print("  Capacity and tariff are both estimates, so treat the rupees as "
              "indicative. The outages are not an estimate: a register that "
              "does not move has not generated.")

    _write(findings, as_of)
    print(f"\nWritten {OUT.relative_to(config.ROOT)}")
    try:
        _figure(plants, findings, as_of)
        print(f"Figure:  {FIGURE.relative_to(config.ROOT)}")
    except Exception as exc:  # noqa: BLE001 - a figure must not fail the report
        print(f"Figure skipped: {exc}")

    _hindsight(plants, every_month)
    return 0


def _months_between(start: str, end: str) -> int:
    return (int(end[:4]) - int(start[:4])) * 12 + (int(end[5:]) - int(start[5:]))


def _hindsight(plants, every_month) -> None:
    """Replay the alarm month by month: when would it first have spoken?"""
    print("\nIf this had been running from the start")
    first_seen: dict[int, tuple[str, str]] = {}
    for month in every_month:
        for finding in alarm.assess(plants, month):
            if finding.status in (alarm.STOPPED, alarm.COLLAPSED,
                                  alarm.UNDERPERFORMING):
                first_seen.setdefault(finding.meter, (month, finding.location))

    if not first_seen:
        print("  nothing would have been flagged at any point in the record")
        return

    for meter, (month, location) in sorted(first_seen.items(), key=lambda kv: kv[1][0]):
        behind = _months_between(month, every_month[-1])
        print(f"  {month}  {location[:38]:<40} "
              f"{behind} months before the end of the record")
    print("\n  The data to do this was in the workbooks the whole time.")


def _write(findings, as_of: str) -> None:
    with OUT.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=[
            "as_of", "meter", "location", "status", "severity", "detail",
            "months_idle", "lost_kwh", "lost_inr", "share_now", "share_usual",
            "first_flagged"])
        writer.writeheader()
        for f in findings:
            writer.writerow({
                "as_of": as_of, "meter": f.meter, "location": f.location,
                "status": f.status, "severity": f.severity, "detail": f.detail,
                "months_idle": f.months_idle, "lost_kwh": round(f.lost_kwh, 1),
                "lost_inr": round(f.lost_inr, 0),
                "share_now": round(f.share_now, 5) if f.share_now else "",
                "share_usual": round(f.share_usual, 5) if f.share_usual else "",
                "first_flagged": f.first_flagged or "",
            })


def _figure(plants, findings, as_of: str) -> None:
    """Every plant, every month, coloured by how it did *that* month.

    An earlier version coloured each row by the plant's status today, which
    made Director's Lodge look dead for the whole record when it was healthy
    for its first six months. Shading each month against the plant's own
    baseline shows the moment it fell over, which is the point of the chart.
    """
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch

    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    months = alarm.months_in(plants)
    shares = alarm.fleet_shares(plants)
    status = {f.meter: f.status for f in findings}

    RANK = {"high": 0, "medium": 1, "low": 2, "none": 3}
    ordered = sorted(
        plants.items(),
        key=lambda kv: (RANK[alarm.SEVERITY[status[kv[0]]]],
                        status[kv[0]], kv[1].location))

    # thresholds shared with the alarm itself, so the picture cannot drift
    # from the verdict
    BANDS = [
        (config.COLLAPSE_RATIO, "#000000", "below 5% of its own baseline"),
        (config.UNDERPERFORMANCE_RATIO, "#888888", "5-60% of baseline"),
        (float("inf"), "#DCDCDC", "generating normally"),
    ]

    def colour(meter, month, baseline):
        if month not in shares or meter not in shares[month]:
            return "#FFFFFF"
        if baseline is None or baseline <= 0:
            return "#DCDCDC"
        ratio = shares[month][meter] / baseline
        for limit, shade, _ in BANDS:
            if ratio < limit:
                return shade
        return "#DCDCDC"

    fig, ax = plt.subplots(figsize=(9.5, 0.32 * len(ordered) + 2.4))
    for row, (meter, plant) in enumerate(ordered):
        seen = [m for m in months if m in shares and meter in shares[m]]
        baseline = (alarm.baseline_share(meter, seen, shares)
                    if len(seen) >= config.MIN_MONTHS_FOR_BASELINE else None)
        for col, month in enumerate(months):
            ax.add_patch(plt.Rectangle(
                (col, row), 1, 1, facecolor=colour(meter, month, baseline),
                edgecolor="#CCCCCC", linewidth=0.4))

    ax.set_xlim(0, len(months))
    ax.set_ylim(0, len(ordered))
    ax.set_yticks([r + 0.5 for r in range(len(ordered))])
    ax.set_yticklabels([p.location[:32] for _, p in ordered], fontsize=7)
    step = max(1, len(months) // 14)
    ax.set_xticks([c + 0.5 for c in range(0, len(months), step)])
    ax.set_xticklabels([months[c] for c in range(0, len(months), step)],
                       fontsize=7, rotation=90)
    ax.invert_yaxis()
    ax.set_title(
        f"Campus solar plants, month by month, as of {as_of}\n"
        "each month shaded against that plant's own opening baseline",
        fontsize=9, loc="left")
    ax.legend(handles=[Patch(facecolor=c, edgecolor="#CCCCCC", label=l)
                       for _, c, l in BANDS]
                      + [Patch(facecolor="#FFFFFF", edgecolor="#CCCCCC",
                               label="nothing recorded (dead plant or unread meter)")],
              loc="upper center", bbox_to_anchor=(0.5, -0.06), ncol=2,
              frameon=False, fontsize=7.5)
    for side in ("top", "right", "left", "bottom"):
        ax.spines[side].set_visible(False)
    ax.tick_params(length=0)
    fig.tight_layout()
    fig.savefig(FIGURE, dpi=200, bbox_inches="tight")
    plt.close(fig)


if __name__ == "__main__":
    raise SystemExit(main())
